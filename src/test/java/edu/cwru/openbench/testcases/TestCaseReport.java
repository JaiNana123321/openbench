package edu.cwru.openbench.testcases;

import edu.cwru.openbench.testcases.TestCaseDocument.Area;
import edu.cwru.openbench.testcases.TestCaseDocument.Requirement;
import edu.cwru.openbench.testcases.TestCaseDocument.TestCase;
import java.util.ArrayList;
import java.util.Collection;
import java.util.EnumMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.function.Function;
import java.util.stream.Collectors;

/**
 * The run report in Markdown: what every functional test case's automated tests did in one test run. Pure, so a
 * unit test pins it; {@link TestCaseReportListener} feeds it the run.
 */
public final class TestCaseReport {

    /** What one test, or every test of one class tagged on the class, did in the run. */
    public enum Outcome { PASSED, FAILED, SKIPPED }

    /**
     * One tagged test, or one tagged class ({@code method} null), and its outcome. {@code note} says why it was
     * skipped or how it failed, or is null.
     */
    public record TestRun(String testClass, String method, boolean partial, Outcome outcome, int tests, String note) {

        String label() {
            String name = method == null ? "`" + testClass + "` (" + (tests == 1 ? "1 test" : "all " + tests + " tests") + ")"
                    : "`" + testClass + "`: " + method;
            String mark = switch (outcome) {
                case PASSED -> "";
                case FAILED -> " **FAILED**";
                case SKIPPED -> " (disabled" + (note == null || note.isBlank() ? "" : ": " + note) + ")";
            };
            return name + (partial ? " [part]" : "") + mark;
        }
    }

    /** A case's result in the run, in report order. */
    public enum Status {
        PASSED("Passed"), PASSED_PARTIAL("Passed (partial)"), FAILED("Failed"), NOT_AUTOMATED("Not automated");

        final String label;

        Status(String label) {
            this.label = label;
        }

        @Override
        public String toString() {
            return label;
        }
    }

    private static final List<String> PRIORITIES = List.of("High", "Medium", "Low");

    private TestCaseReport() {}

    /**
     * A case is Failed if any of its tests failed; else Passed if a test running all of it passed; else Passed
     * (partial) if a test running part of it passed; else Not automated (no test, or only disabled ones).
     */
    public static Status status(Collection<TestRun> runs) {
        if (runs.stream().anyMatch(r -> r.outcome() == Outcome.FAILED)) {
            return Status.FAILED;
        }
        if (runs.stream().anyMatch(r -> r.outcome() == Outcome.PASSED && !r.partial())) {
            return Status.PASSED;
        }
        if (runs.stream().anyMatch(r -> r.outcome() == Outcome.PASSED)) {
            return Status.PASSED_PARTIAL;
        }
        return Status.NOT_AUTOMATED;
    }

    /** The report for the document and the runs of the tagged tests by case key. */
    public static String render(TestCaseDocument document, Map<String, List<TestRun>> runsByKey, String build) {
        Map<String, Status> status = new LinkedHashMap<>();
        for (TestCase c : document.cases()) {
            status.put(c.key(), status(runsByKey.getOrDefault(c.key(), List.of())));
        }
        StringBuilder out = new StringBuilder();
        out.append("# Functional test cases: run report\n\n");
        out.append("Generated by `mvn verify` from `docs/test-cases/sections/cases/*.tex` and the `@Verifies` tests of this run")
                .append(build == null ? "" : ", build " + build).append(". A case's status is that of the tests that ran it: ")
                .append("Failed if any failed; Passed if a test for the whole case passed; Passed (partial) if only tests ")
                .append("marked [part] passed; Not automated if no test ran it. See TESTING.md.\n\n");

        summary(out, document, status, runsByKey);
        for (Area area : document.areas()) {
            areaTable(out, area, document, status, runsByKey);
        }
        requirementTable(out, document, status);
        return out.toString();
    }

    private static void summary(StringBuilder out, TestCaseDocument document, Map<String, Status> status,
            Map<String, List<TestRun>> runsByKey) {
        Map<Status, Long> byStatus = countByStatus(document.cases(), status);
        out.append("## Summary\n\n");
        out.append(document.cases().size()).append(" test cases: ")
                .append(byStatus.entrySet().stream().map(e -> e.getValue() + " " + e.getKey()).collect(Collectors.joining(", ")))
                .append(".\n\n");
        out.append("| Priority | Cases |");
        for (Status s : Status.values()) {
            out.append(' ').append(s).append(" |");
        }
        out.append("\n|---|---:|").append("---:|".repeat(Status.values().length)).append('\n');
        List<String> priorities = new ArrayList<>(PRIORITIES);
        document.cases().stream().map(TestCase::priority).distinct().filter(p -> !priorities.contains(p)).forEach(priorities::add);
        for (String priority : priorities) {
            List<TestCase> cases = document.cases().stream().filter(c -> c.priority().equals(priority)).toList();
            if (!cases.isEmpty()) {
                countRow(out, priority, cases, status);
            }
        }
        countRow(out, "**All**", document.cases(), status);

        List<TestRun> runs = runsByKey.values().stream().flatMap(List::stream).distinct().toList();
        long failed = runs.stream().filter(r -> r.outcome() == Outcome.FAILED).count();
        long skipped = runs.stream().filter(r -> r.outcome() == Outcome.SKIPPED).count();
        out.append("\nTagged tests in this run: ").append(runs.size()).append(" (by method, or by class where the class is tagged), ")
                .append(failed).append(" failed, ").append(skipped).append(" disabled.\n\n");
    }

    private static void countRow(StringBuilder out, String label, List<TestCase> cases, Map<String, Status> status) {
        Map<Status, Long> counts = countByStatus(cases, status);
        out.append("| ").append(label).append(" | ").append(cases.size()).append(" |");
        for (Status s : Status.values()) {
            out.append(' ').append(counts.get(s)).append(" |");
        }
        out.append('\n');
    }

    private static Map<Status, Long> countByStatus(List<TestCase> cases, Map<String, Status> status) {
        Map<Status, Long> counts = new EnumMap<>(Status.class);
        for (Status s : Status.values()) {
            counts.put(s, 0L);
        }
        cases.forEach(c -> counts.merge(status.get(c.key()), 1L, Long::sum));
        return counts;
    }

    private static void areaTable(StringBuilder out, Area area, TestCaseDocument document, Map<String, Status> status,
            Map<String, List<TestRun>> runsByKey) {
        List<TestCase> cases = document.cases().stream().filter(c -> c.area().equals(area.code())).toList();
        out.append("## ").append(area.code()).append(": ").append(cell(area.title())).append("\n\n");
        out.append("| Case | Key | Title | Priority | Requirements | Status | Tests |\n");
        out.append("|---|---|---|---|---|---|---|\n");
        for (TestCase c : cases) {
            List<TestRun> runs = runsByKey.getOrDefault(c.key(), List.of());
            out.append("| ").append(c.id())
                    .append(" | `").append(c.key()).append('`')
                    .append(" | ").append(cell(c.title()))
                    .append(" | ").append(c.priority())
                    .append(" | ").append(String.join(", ", c.requirements()))
                    .append(" | ").append(status.get(c.key()))
                    .append(" | ").append(runs.isEmpty() ? "" : cell(runs.stream().map(TestRun::label).collect(Collectors.joining("; "))))
                    .append(" |\n");
        }
        out.append('\n');
    }

    private static void requirementTable(StringBuilder out, TestCaseDocument document, Map<String, Status> status) {
        Map<String, TestCase> byKey = document.cases().stream()
                .collect(Collectors.toMap(TestCase::key, Function.identity(), (a, b) -> a, LinkedHashMap::new));
        out.append("## Requirements\n\n");
        out.append("Each functional requirement of the SRS short edition (Section 4), the test cases that cover it, and ")
                .append("the best status among them: Passed means at least one automated case for it passed in full.\n\n");
        out.append("| Requirement | Feature | Scope | Test cases | Best status |\n");
        out.append("|---|---|---|---|---|\n");
        for (Requirement r : document.requirements()) {
            List<TestCase> covering = byKey.values().stream().filter(c -> c.requirements().contains(r.id())).toList();
            Status best = covering.stream().map(c -> status.get(c.key()))
                    .min((a, b) -> rank(a) - rank(b)).orElse(Status.NOT_AUTOMATED);
            out.append("| ").append(r.id())
                    .append(" | ").append(cell(r.group()))
                    .append(" | ").append(r.stretch() ? "Stretch" : "Release 1")
                    .append(" | ").append(covering.isEmpty() ? "Not covered"
                            : covering.stream().map(c -> c.id() + " (" + status.get(c.key()) + ")").collect(Collectors.joining(", ")))
                    .append(" | ").append(best)
                    .append(" |\n");
        }
    }

    /** Passed before Passed (partial) before Failed before Not automated: did any case for it pass? */
    private static int rank(Status s) {
        return switch (s) {
            case PASSED -> 0;
            case PASSED_PARTIAL -> 1;
            case FAILED -> 2;
            case NOT_AUTOMATED -> 3;
        };
    }

    private static String cell(String text) {
        return text.replace("|", "\\|").replace("\n", " ");
    }
}
