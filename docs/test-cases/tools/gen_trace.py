#!/usr/bin/env python3
"""Generate the requirement-to-test-case traceability matrix (LaTeX) for the test case document.

Reads every functional requirement (\\fr[Tag]{Id}{...}) of the SRS short edition, grouped by its \\subsection, and every
test case (\\begin{testcase}{key}{Title}{Req.Id, Req.Id}) of sections/cases/*.tex in file order, then emits one longtable
row per requirement listing the test cases that cover it, or a red "Not covered" marker. Each row carries the label
req:<Id> that \\req{Id} links to.

Warnings on stderr: a test case naming an identifier that is not a requirement of the SRS short edition (a typo, or a
full-edition identifier), and a coverage summary.

Usage: gen_trace.py SRS_FEATURES_TEX CASES_DIR OUT_TEX
"""
import re
import sys
from pathlib import Path


def braced(text, i):
    """Return (content, index after the closing brace) for the brace group starting at text[i] == '{'."""
    assert text[i] == "{", text[i : i + 20]
    depth = 0
    for j in range(i, len(text)):
        if text[j] == "{":
            depth += 1
        elif text[j] == "}":
            depth -= 1
            if depth == 0:
                return text[i + 1 : j], j + 1
    raise ValueError("unbalanced braces")


def strip_comments(text):
    return re.sub(r"(?<!\\)%.*", "", text)


def requirements(srs_tex):
    """[(group, id, tag)] in document order."""
    text = strip_comments(srs_tex)
    out, group = [], ""
    for m in re.finditer(r"\\subsection\{([^}]*)\}|\\fr(?:\[([^\]]*)\])?\{([^}]*)\}", text):
        if m.group(1) is not None:
            group = m.group(1)
        else:
            out.append((group, m.group(3).strip(), (m.group(2) or "").strip()))
    return out


def test_cases(cases_dir):
    """[(file, key, [req ids])] in file and document order."""
    out = []
    for path in sorted(Path(cases_dir).glob("*.tex")):
        text = strip_comments(path.read_text(encoding="utf-8"))
        for m in re.finditer(r"\\begin\{testcase\}", text):
            key, i = braced(text, m.end())
            _title, i = braced(text, i)
            reqs, _ = braced(text, i)
            out.append((path.name, key.strip(), [r.strip() for r in reqs.split(",") if r.strip()]))
    return out


def main(argv):
    if len(argv) != 4:
        sys.exit(__doc__)
    reqs = requirements(Path(argv[1]).read_text(encoding="utf-8"))
    cases = test_cases(argv[2])
    known = {rid for _, rid, _ in reqs}

    covering = {rid: [] for rid in known}
    for fname, key, ids in cases:
        for rid in ids:
            if rid in covering:
                covering[rid].append(key)
            else:
                print(f"gen_trace: {fname}: test case '{key}' names '{rid}', not a requirement of the SRS short edition",
                      file=sys.stderr)

    covered = sum(1 for rid in known if covering[rid])
    release1 = [rid for _, rid, tag in reqs if tag != "Stretch"]
    covered_r1 = sum(1 for rid in release1 if covering[rid])

    out = [
        r"% Generated by tools/gen_trace.py; do not edit. Edit the requirement list of each test case instead.",
        r"\noindent %d of the %d Release~1 requirements and %d of the %d requirements in scope are covered by at least one "
        r"test case; the document has %d test case%s." % (covered_r1, len(release1), covered, len(reqs), len(cases),
                                                          "" if len(cases) == 1 else "s"),
        r"\par\medskip",
        r"{\footnotesize",
        r"\begin{longtable}{@{}L{0.40\textwidth}L{0.09\textwidth}L{0.45\textwidth}@{}}",
        r"\toprule \textbf{Requirement} & \textbf{Scope} & \textbf{Test cases} \\ \midrule \endfirsthead",
        r"\toprule \textbf{Requirement} & \textbf{Scope} & \textbf{Test cases} \\ \midrule \endhead",
        r"\bottomrule \endfoot",
    ]
    group = None
    for g, rid, tag in reqs:
        if g != group:
            if group is not None:
                out.append(r"\midrule")
            out.append(r"\multicolumn{3}{@{}l}{\textit{%s}} \\" % g)
            group = g
        cell = ", ".join(r"\TC{%s}" % k for k in covering[rid]) or r"\textcolor{red!70!black}{Not covered}"
        # The anchor goes after the text: in vertical mode at the start of a p cell it would push the row down a line.
        out.append(r"\textbf{%s}\phantomsection\label{req:%s} & %s & %s \\"
                   % (rid, rid, "Stretch" if tag == "Stretch" else "Release~1", cell))
    out += [r"\end{longtable}", r"}"]
    Path(argv[3]).write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"gen_trace: {covered_r1}/{len(release1)} Release 1 and {covered}/{len(reqs)} in-scope requirements covered "
          f"by {len(cases)} test cases", file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv)
