#!/usr/bin/env python3
"""Generate the short edition's copy of one test case file (LaTeX).

Copies sections/cases/NN-<feature>.tex, replacing every test case whose Priority field is one of the dropped priorities
(Medium by default) with \\tcomitted{key}{Title}, and ends the file with \\tcomittedlist. \\tcomitted advances the test
case counter and records the case, so the cases kept keep the numbers they have in the full edition and a \\TC{key}
reference to a dropped case still resolves; \\tcomittedlist prints the dropped cases of the area as one "Full edition
only" line. The case text itself is never copied by hand, so the two editions cannot drift apart.

Fails if a test case has no Priority field.

Usage: gen_short.py IN_TEX OUT_TEX [DROPPED_PRIORITY ...]
"""
import re
import sys
from pathlib import Path


def braced(text, i):
    """Return (content, index after the closing brace) for the brace group starting at text[i] == '{'."""
    assert text[i] == "{", text[i : i + 20]
    depth = 0
    for j in range(i, len(text)):
        if text[j] == "{":
            depth += 1
        elif text[j] == "}":
            depth -= 1
            if depth == 0:
                return text[i + 1 : j], j + 1
    raise ValueError("unbalanced braces")


def main(argv):
    if len(argv) < 3:
        sys.exit(__doc__)
    src, dst = Path(argv[1]), Path(argv[2])
    dropped = set(argv[3:]) or {"Medium"}
    text = src.read_text(encoding="utf-8")

    out, pos, kept, omitted = [], 0, 0, 0
    begin, end = r"\begin{testcase}", r"\end{testcase}"
    while (start := text.find(begin, pos)) != -1:
        stop = text.index(end, start) + len(end)
        key, i = braced(text, start + len(begin))
        title, _ = braced(text, i)
        block = text[start:stop]
        m = re.search(r"\\tcfield\{Priority\}\{([^}]*)\}", block)
        if not m:
            sys.exit(f"gen_short: {src.name}: test case '{key}' has no Priority field")
        out.append(text[pos:start])
        if m.group(1).strip() in dropped:
            out.append(r"\tcomitted{%s}{%s}" % (key, title))
            omitted += 1
        else:
            out.append(block)
            kept += 1
        pos = stop
    out.append(text[pos:].rstrip("\n") + "\n\\tcomittedlist\n")

    header = ("%% Generated by tools/gen_short.py from sections/cases/%s; do not edit. Test cases of priority %s are kept "
              "in the full edition only.\n" % (src.name, " or ".join(sorted(dropped))))
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(header + "".join(out), encoding="utf-8")
    print(f"gen_short: {src.name}: {kept} kept, {omitted} in the full edition only", file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv)
